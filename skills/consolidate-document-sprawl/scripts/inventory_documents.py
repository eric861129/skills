#!/usr/bin/env python3
"""唯讀盤點專案文件，輸出可供後續人工判讀的機械化事證。"""

from __future__ import annotations

import argparse
from collections import defaultdict
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
from typing import Any
from urllib.parse import unquote, urlsplit


DEFAULT_EXTENSIONS = {".adoc", ".md", ".mdx", ".rst", ".txt"}
DEFAULT_EXCLUDED_DIRECTORIES = {
    ".cache",
    ".git",
    ".hg",
    ".svn",
    ".venv",
    "bin",
    "build",
    "coverage",
    "dist",
    "node_modules",
    "obj",
    "vendor",
    "venv",
}
GENERATED_MARKERS = (
    "auto-generated",
    "autogenerated",
    "automatically generated",
    "do not edit",
    "generated file",
    "此檔案由程式產生",
    "請勿手動修改",
)
LINK_PATTERN = re.compile(r"!?\[[^\]]*\]\(([^)]+)\)")
HEADING_PATTERN = re.compile(r"^#{1,6}\s+(.+?)\s*$", re.MULTILINE)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="唯讀盤點文件路徑、雜湊、標題、Git 狀態、連結與生成線索。"
    )
    parser.add_argument("root", help="要盤點的專案根目錄")
    parser.add_argument(
        "--format",
        choices=("json", "text"),
        default="json",
        help="輸出格式，預設為 json",
    )
    parser.add_argument(
        "--extensions",
        default=",".join(sorted(DEFAULT_EXTENSIONS)),
        help="以逗號分隔的副檔名，例如 .md,.mdx,.rst",
    )
    parser.add_argument(
        "--exclude",
        action="append",
        default=[],
        metavar="RELATIVE_PATH",
        help="額外排除的目錄名稱或根目錄相對路徑，可重複使用",
    )
    parser.add_argument(
        "--max-bytes",
        type=int,
        default=5_000_000,
        help="單一文件讀取上限，預設 5000000 bytes",
    )
    return parser.parse_args()


def normalize_extensions(raw: str) -> set[str]:
    extensions: set[str] = set()
    for item in raw.split(","):
        item = item.strip().lower()
        if not item:
            continue
        extensions.add(item if item.startswith(".") else f".{item}")
    if not extensions:
        raise ValueError("至少需要一個文件副檔名")
    return extensions


def normalize_relative(path: Path) -> str:
    return path.as_posix()


def should_exclude_directory(
    directory: Path, root: Path, additional_excludes: set[str]
) -> bool:
    relative = normalize_relative(directory.relative_to(root))
    if directory.name.lower() in DEFAULT_EXCLUDED_DIRECTORIES:
        return True
    return any(
        relative == excluded or relative.startswith(f"{excluded}/")
        for excluded in additional_excludes
    )


def collect_document_paths(
    root: Path, extensions: set[str], additional_excludes: set[str]
) -> list[Path]:
    documents: list[Path] = []
    for current, directories, files in os.walk(root, followlinks=False):
        current_path = Path(current)
        directories[:] = sorted(
            directory
            for directory in directories
            if not should_exclude_directory(
                current_path / directory, root, additional_excludes
            )
        )
        for filename in sorted(files):
            path = current_path / filename
            if path.suffix.lower() in extensions:
                documents.append(path)
    return documents


def run_git(root: Path, *arguments: str) -> bytes | None:
    try:
        result = subprocess.run(
            ["git", "-C", str(root), *arguments],
            check=False,
            capture_output=True,
        )
    except FileNotFoundError:
        return None
    return result.stdout if result.returncode == 0 else None


def collect_git_metadata(root: Path) -> tuple[set[str] | None, dict[str, str]]:
    tracked_output = run_git(root, "ls-files", "-z")
    if tracked_output is None:
        return None, {}

    tracked = {
        item.decode("utf-8", errors="replace").replace("\\", "/")
        for item in tracked_output.split(b"\0")
        if item
    }
    status_output = run_git(
        root, "status", "--porcelain=v1", "-z", "--untracked-files=all"
    )
    statuses: dict[str, str] = {}
    if status_output is not None:
        entries = [entry for entry in status_output.split(b"\0") if entry]
        index = 0
        while index < len(entries):
            entry = entries[index].decode("utf-8", errors="replace")
            if len(entry) >= 4:
                status = entry[:2]
                path = entry[3:].replace("\\", "/")
                statuses[path] = status
                if "R" in status or "C" in status:
                    index += 1
            index += 1
    return tracked, statuses


def decode_utf8(data: bytes) -> tuple[str | None, str]:
    try:
        return data.decode("utf-8-sig"), "utf-8"
    except UnicodeDecodeError:
        return None, "non-utf8-or-invalid"


def extract_title_and_heading_count(text: str) -> tuple[str | None, int]:
    headings = HEADING_PATTERN.findall(text)
    return (headings[0].strip() if headings else None, len(headings))


def infer_hints(path: Path, relative_path: str, text: str) -> list[str]:
    hints: set[str] = set()
    lowered_path = relative_path.lower()
    lowered_text = text[:4096].lower()
    path_parts = {part.lower() for part in path.parts}
    stem = path.stem.lower()

    if "generated" in path_parts or "autogen" in path_parts:
        hints.add("generated-path")
    if any(marker in lowered_text for marker in GENERATED_MARKERS):
        hints.add("generated-marker")
    if "archive" in path_parts or "archived" in path_parts:
        hints.add("archive-path")
    if "handoff" in stem:
        hints.add("handoff-name")
    if "summary" in stem:
        hints.add("summary-name")
    if "final" in stem:
        hints.add("final-name")
    if re.search(r"(?:^|[-_.])v\d+(?:$|[-_.])", stem):
        hints.add("versioned-name")
    if re.search(r"(?:^|[-_.])(?:draft|copy|backup|old)(?:$|[-_.])", stem):
        hints.add("temporary-name")
    if re.search(r"(?:^|[-_.])phase[-_.]?\d*", stem):
        hints.add("phase-name")
    if "/generated/" in f"/{lowered_path}/":
        hints.add("generated-path")
    return sorted(hints)


def clean_link_target(raw_target: str) -> str:
    target = raw_target.strip()
    if target.startswith("<") and ">" in target:
        return target[1 : target.index(">")]
    return target.split(maxsplit=1)[0]


def inspect_local_links(text: str, source: Path, root: Path) -> list[dict[str, str]]:
    links: list[dict[str, str]] = []
    for raw_target in LINK_PATTERN.findall(text):
        target = clean_link_target(raw_target)
        parsed = urlsplit(target)
        if (
            not target
            or target.startswith("#")
            or parsed.scheme
            or parsed.netloc
            or target.startswith("//")
        ):
            continue

        decoded_path = unquote(parsed.path).replace("\\", "/")
        if not decoded_path:
            continue
        resolved = (
            root / decoded_path.lstrip("/")
            if decoded_path.startswith("/")
            else source.parent / decoded_path
        ).resolve()
        try:
            relative = normalize_relative(resolved.relative_to(root))
            status = "ok" if resolved.exists() else "missing"
        except ValueError:
            relative = str(resolved)
            status = "outside-root"
        links.append(
            {
                "target": target,
                "resolved_path": relative,
                "status": status,
            }
        )
    return links


def build_report(
    root: Path,
    extensions: set[str],
    additional_excludes: set[str],
    max_bytes: int,
) -> dict[str, Any]:
    tracked, statuses = collect_git_metadata(root)
    documents: list[dict[str, Any]] = []
    skipped: list[dict[str, Any]] = []
    hashes: defaultdict[str, list[str]] = defaultdict(list)
    incoming_links: defaultdict[str, list[str]] = defaultdict(list)

    for path in collect_document_paths(root, extensions, additional_excludes):
        relative_path = normalize_relative(path.relative_to(root))
        size = path.stat().st_size
        if size > max_bytes:
            skipped.append(
                {
                    "path": relative_path,
                    "reason": "max-bytes-exceeded",
                    "size_bytes": size,
                }
            )
            continue

        data = path.read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        text, encoding = decode_utf8(data)
        if text is None:
            title = None
            heading_count = 0
            line_count = None
            links: list[dict[str, str]] = []
            hints: list[str] = []
        else:
            title, heading_count = extract_title_and_heading_count(text)
            line_count = len(text.splitlines())
            links = inspect_local_links(text, path, root)
            hints = infer_hints(path, relative_path, text)
            for link in links:
                if link["status"] == "ok":
                    incoming_links[link["resolved_path"]].append(relative_path)

        hashes[digest].append(relative_path)
        documents.append(
            {
                "path": relative_path,
                "title": title,
                "size_bytes": size,
                "line_count": line_count,
                "heading_count": heading_count,
                "sha256": digest,
                "encoding": encoding,
                "git": {
                    "tracked": None if tracked is None else relative_path in tracked,
                    "status": statuses.get(relative_path, ""),
                },
                "hints": hints,
                "local_links": links,
                "incoming_links": [],
            }
        )

    for document in documents:
        document["incoming_links"] = sorted(incoming_links[document["path"]])

    duplicate_groups = [
        {"sha256": digest, "paths": sorted(paths)}
        for digest, paths in sorted(hashes.items())
        if len(paths) > 1
    ]
    missing_links = sum(
        1
        for document in documents
        for link in document["local_links"]
        if link["status"] == "missing"
    )
    encoding_errors = sum(
        1 for document in documents if document["encoding"] != "utf-8"
    )

    return {
        "schema_version": "1.0",
        "root": str(root),
        "read_only": True,
        "limitations": [
            "完全相同雜湊不代表文件可以安全刪除。",
            "此工具不判斷語意重複、內容正確性、權威來源、法規保存或外部引用。",
            "hints 只供盤點排序，不得單獨作為刪除、搬移或改名依據。",
        ],
        "summary": {
            "document_count": len(documents),
            "skipped_count": len(skipped),
            "exact_duplicate_group_count": len(duplicate_groups),
            "missing_local_link_count": missing_links,
            "encoding_error_count": encoding_errors,
            "git_repository_detected": tracked is not None,
        },
        "documents": sorted(documents, key=lambda item: item["path"]),
        "exact_duplicate_groups": duplicate_groups,
        "skipped": sorted(skipped, key=lambda item: item["path"]),
    }


def render_text(report: dict[str, Any]) -> str:
    summary = report["summary"]
    lines = [
        f"Root: {report['root']}",
        f"Documents: {summary['document_count']}",
        f"Skipped: {summary['skipped_count']}",
        f"Exact duplicate groups: {summary['exact_duplicate_group_count']}",
        f"Missing local links: {summary['missing_local_link_count']}",
        f"Encoding errors: {summary['encoding_error_count']}",
    ]
    for group in report["exact_duplicate_groups"]:
        lines.append(f"DUPLICATE {group['sha256']}: {', '.join(group['paths'])}")
    for document in report["documents"]:
        for link in document["local_links"]:
            if link["status"] != "ok":
                lines.append(
                    f"LINK {link['status']} {document['path']} -> {link['target']}"
                )
    return "\n".join(lines)


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    if hasattr(sys.stderr, "reconfigure"):
        sys.stderr.reconfigure(encoding="utf-8")

    args = parse_args()
    root = Path(args.root).expanduser().resolve()
    if not root.is_dir():
        print(f"錯誤：找不到專案目錄：{root}", file=sys.stderr)
        return 2
    if args.max_bytes <= 0:
        print("錯誤：--max-bytes 必須大於 0", file=sys.stderr)
        return 2

    try:
        extensions = normalize_extensions(args.extensions)
    except ValueError as error:
        print(f"錯誤：{error}", file=sys.stderr)
        return 2
    additional_excludes = {
        item.strip().replace("\\", "/").strip("/")
        for item in args.exclude
        if item.strip()
    }

    report = build_report(root, extensions, additional_excludes, args.max_bytes)
    if args.format == "json":
        json.dump(report, sys.stdout, ensure_ascii=False, indent=2)
        sys.stdout.write("\n")
    else:
        print(render_text(report))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
